async function start(){
 try{
  const res=await fetch(import.meta.env.BASE_URL+'data/forbidden-city.json');
  if(!res.ok)throw new Error('Không tải được dữ liệu bản đồ ('+res.status+')');
  setData(await res.json());
  buildDom();
  buildScene();
  buildSky();
  buildUtils();
  buildTextures();
  buildWeather();
  buildOrnaments();
  buildPrimitives();
  buildCourts();
  buildMoat();
  buildRampart();
  buildWumen();
  buildWater();
  buildTaihe();
  buildLandmarks();
  buildWalls();
  buildMappedBuildings();
  decorateOpenings();
  buildLandscape();
  buildTrees();
  buildVegetation();
  buildProps();
  buildFinalize();
  buildGame1();
  buildRooms();
  buildGame2();
  buildNpcs();
  buildRoyalNpcs();
  buildWeatherFx();
  buildBirds();
  buildCats();
  buildSmoke();
  buildLanterns();
  buildGame4();
 }catch(error){document.getElementById('status').textContent='Không mở được cảnh 3D. '+error.message;console.error(error)}
}
start();
